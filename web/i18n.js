// 顶层 const 不会挂到 window 上（跨脚本只能靠全局词法绑定），这里显式给一份
window.ParlzI18n = (() => {
  const base = I18N["en-US"];
  const table = (lang) => I18N[lang] || base;
  const get = (lang, key) => {
    const d = table(lang);
    if (key in d) return d[key];
    return key in base ? base[key] : key;
  };
  const t = (key, vars) => {
    let s = get(document.documentElement.dataset.lang || "en-US", key);
    if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
  };
  const apply = (lang) => {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = get(lang, el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = get(lang, el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      el.getAttribute("data-i18n-attr").split(";").forEach((pair) => {
        const i = pair.indexOf(":");
        if (i > 0) el.setAttribute(pair.slice(0, i).trim(), get(lang, pair.slice(i + 1).trim()));
      });
    });
    const page = document.body.getAttribute("data-page");
    if (page) {
      document.title = get(lang, page + ".title");
      const md = document.querySelector('meta[name="description"]');
      if (md) md.setAttribute("content", get(lang, page + ".desc"));
    }
    const r = document.documentElement;
    r.lang = lang;
    r.dataset.lang = lang;
    r.dir = PARLZ_RTL.indexOf(lang) >= 0 ? "rtl" : "ltr";
    r.classList.remove("i18n-wait");
  };
  return { t, apply, langs: PARLZ_LANGS, rtl: PARLZ_RTL };
})();
